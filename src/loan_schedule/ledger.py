"""Immutable repayment facts plus knowledge-time snapshots.

Two responsibilities are kept apart on purpose:

* **Fact storage** appends every source version exactly once, keeps the source
  byte SHA-256 of every successful batch, and hands out a contiguous
  ``knowledge_seq``.  Rows in ``batches``, ``raw_versions``, ``knowledge`` and
  ``contract`` are protected against UPDATE/DELETE by SQLite triggers.
* **Derived state** (the effective event set, every per-event allocation and
  every period debt) is always recomputed from the raw versions visible at a
  given ``knowledge_seq``.  Allocations are never copied between commits, so a
  correction cannot leave a stale allocation behind, and an old cutoff can
  still be regenerated byte-for-byte from the raw versions of its own seq.
"""
from datetime import datetime, timezone
from .allocation import allocate, reconcile
from .common import ident, only, require
from . import sqlstore

BATCH_KEYS='batch_id events'
RECEIPT_KEYS='event_id rev op kind period amount'
REVERSAL_KEYS='event_id rev op kind period target'
VOID_KEYS='event_id rev op'
REV_MAX=2**63-1


def _integer(value,minimum,maximum,field):
    if type(value) is not int:
        raise ValueError('%s must be an integer' % field)
    if not minimum<=value<=maximum:
        raise ValueError('%s must be within %d..%d' % (field,minimum,maximum))
    return value


def _label(item,index):
    if isinstance(item,dict) and type(item.get('event_id')) is str and item['event_id']:
        return 'events[%d] event_id %r' % (index,item['event_id'])
    return 'events[%d]' % index


def parse_batch(data,periods):
    """Validate the batch envelope and every event against the contract.

    Array order is irrelevant: the batch is normalised to one version per
    event_id.  Rules that depend on the committed predecessor (revision
    continuity, kind immutability, reference validity, overpayment) are checked
    later against the database.  Unknown fields, duplicate keys, booleans
    posing as integers and non-finite numbers are rejected by the strict JSON
    reader in :mod:`loan_schedule.common`.
    """
    require(data,BATCH_KEYS)
    batch_id=ident(data['batch_id'])
    raw_events=data['events']
    if not isinstance(raw_events,list):raise ValueError('events must be an array')
    if len(raw_events)>20000:raise ValueError('events exceeds 20000')
    versions={}
    for index,item in enumerate(raw_events):
        where=_label(item,index)
        try:
            version=_parse_event(item,periods)
        except ValueError as error:
            raise ValueError('%s: %s' % (where,error)) from None
        if version['event_id'] in versions:
            raise ValueError(where+': duplicate event_id %r in one batch' % version['event_id'])
        versions[version['event_id']]=version
    return batch_id,versions


def _parse_event(item,periods):
    if not isinstance(item,dict):raise ValueError('expected object')
    op=item.get('op')
    if op=='void':
        only(item,VOID_KEYS)
        missing=set(VOID_KEYS.split())-set(item)
        if missing:raise ValueError('void requires '+', '.join(sorted(missing)))
        return {'event_id':ident(item['event_id']),'rev':_integer(item['rev'],1,REV_MAX,'rev'),
                'op':'void','kind':None,'period':None,'amount':None,'target':None}
    if op!='upsert':raise ValueError('op must be upsert or void')
    kind=item.get('kind')
    if kind=='receipt':keys=RECEIPT_KEYS
    elif kind=='reversal':keys=REVERSAL_KEYS
    else:raise ValueError('kind must be receipt or reversal')
    only(item,keys)
    missing=set(keys.split())-set(item)
    if missing:raise ValueError(kind+' requires '+', '.join(sorted(missing)))
    event_id=ident(item['event_id'])
    rev=_integer(item['rev'],1,REV_MAX,'rev')
    period=_integer(item['period'],1,periods,'period')
    if kind=='receipt':
        amount=_integer(item['amount'],1,10**12,'amount')
        return {'event_id':event_id,'rev':rev,'op':'upsert','kind':'receipt',
                'period':period,'amount':amount,'target':None}
    target=ident(item['target'])
    if target==event_id:raise ValueError('reversal cannot target itself')
    return {'event_id':event_id,'rev':rev,'op':'upsert','kind':'reversal',
            'period':period,'amount':None,'target':target}


def _current_versions(db,seq):
    """Latest committed version per event as known at ``seq`` (largest rev)."""
    rows=db.execute('''
        SELECT v.event_id,v.rev,v.op,v.kind,v.period,v.amount,v.target
        FROM raw_versions v
        JOIN (SELECT event_id,MAX(rev) AS rev FROM raw_versions
              WHERE seq<=? GROUP BY event_id) latest
          ON latest.event_id=v.event_id AND latest.rev=v.rev
        WHERE v.seq<=?
        ORDER BY v.event_id
    ''',(seq,seq)).fetchall()
    return {event_id:{'event_id':event_id,'rev':rev,'op':op,'kind':kind,'period':period,
                      'amount':amount,'target':target}
            for event_id,rev,op,kind,period,amount,target in rows}


def _meta(db):
    rows=db.execute('SELECT event_id,kind,max_rev FROM event_meta').fetchall()
    return {event_id:{'kind':kind,'max_rev':max_rev} for event_id,kind,max_rev in rows}


def _batch_identity(db,batch_id):
    row=db.execute('SELECT seq,source_sha256,event_count FROM batches WHERE batch_id=?',(batch_id,)).fetchone()
    return None if row is None else {'seq':row[0],'source_sha256':row[1],'event_count':row[2]}


def _effective(versions):
    return [versions[event_id] for event_id in sorted(versions)
            if versions[event_id]['op']=='upsert']


def build_snapshot(db,seq,through_period):
    """One read transaction: batches, current versions and the derived report."""
    contract=sqlstore.load_contract(db)
    batches=[{'seq':row[0],'batch_id':row[1],'source_sha256':row[2],'event_count':row[3]}
             for row in db.execute('SELECT seq,batch_id,source_sha256,event_count FROM batches '
                                   'WHERE seq<=? ORDER BY seq',(seq,))]
    versions=_current_versions(db,seq)
    period_rows,settled=allocate(contract,_effective(versions),through_period)
    totals=reconcile(contract,period_rows,settled)
    events=[{'event_id':event['event_id'],'rev':event['rev'],'kind':event['kind'],
             'period':event['period'],'amount':event['amount'],'target':event['target'],
             'interest_applied':event['interest_applied'],
             'principal_applied':event['principal_applied']}
            for event in settled]
    return {
        'schema_version':2,
        'rounding':'nonnegative half-up to one minor unit, each period, on actual opening principal',
        'loan':dict(contract),
        'known_seq':seq,
        'through_period':through_period,
        'batches':batches,
        'periods':period_rows,
        'events':events,
        'totals':totals,
    }


def validate_and_commit(db,data,source_sha):
    """Validate one batch against the current predecessor and commit it.

    The whole read-validate-write cycle runs under a single ``BEGIN IMMEDIATE``
    transaction so the validation and the commit observe the same predecessor
    state.  A failure rolls back, leaving raw versions, batches and
    ``knowledge_seq`` untouched.  If the caller already owns a transaction, it
    is reused so that extra checks can share the same snapshot.
    """
    if db.in_transaction:
        return _commit(db,data,source_sha)
    with sqlstore.transaction(db):
        return _commit(db,data,source_sha)


def _commit(db,data,source_sha):
    contract=sqlstore.load_contract(db)
    batch_id,versions=parse_batch(data,contract['periods'])
    known=_batch_identity(db,batch_id)
    if known is not None:
        if known['source_sha256']==source_sha:
            return {'batch_id':batch_id,'source_sha256':source_sha,
                    'seq':known['seq'],'event_count':known['event_count'],'duplicate':True}
        raise ValueError('batch_id %r already committed with different source bytes' % batch_id)
    meta=_meta(db)
    seq=sqlstore.latest_seq(db)
    current=_current_versions(db,seq)
    for event_id in sorted(versions):
        version=versions[event_id];previous=current.get(event_id);known_meta=meta.get(event_id)
        if version['op']=='void':
            if previous is None or previous['op']=='void':
                raise ValueError('event_id %r rev %d: void requires an existing non-void version'
                                 % (event_id,version['rev']))
            if version['rev']!=previous['rev']+1:
                raise ValueError('event_id %r rev %d: expected rev %d'
                                 % (event_id,version['rev'],previous['rev']+1))
            continue
        if known_meta is None:
            if version['rev']!=1:
                raise ValueError('event_id %r rev %d: first version must be rev 1'
                                 % (event_id,version['rev']))
        else:
            if version['kind']!=known_meta['kind']:
                raise ValueError('event_id %r: kind cannot change from %s'
                                 % (event_id,known_meta['kind']))
            if version['rev']!=known_meta['max_rev']+1:
                raise ValueError('event_id %r rev %d: expected rev %d'
                                 % (event_id,version['rev'],known_meta['max_rev']+1))
    candidate=dict(current)
    for event_id,version in versions.items():candidate[event_id]=dict(version)
    try:
        period_rows,settled=allocate(contract,_effective(candidate))
        reconcile(contract,period_rows,settled)
    except ValueError as error:
        raise ValueError('batch %r rejected: %s' % (batch_id,error)) from error
    accepted=datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    db.execute('INSERT INTO batches(seq,batch_id,source_sha256,event_count,accepted_at) VALUES(?,?,?,?,?)',
               (seq+1,batch_id,source_sha,len(versions),accepted))
    for event_id in sorted(versions):
        version=versions[event_id]
        db.execute('INSERT INTO raw_versions(seq,event_id,rev,op,kind,period,amount,target) '
                   'VALUES(?,?,?,?,?,?,?,?)',
                   (seq+1,event_id,version['rev'],version['op'],version['kind'],
                    version['period'],version['amount'],version['target']))
        known_kind=meta[event_id]['kind'] if event_id in meta else version['kind']
        db.execute('INSERT INTO event_meta(event_id,kind,max_seq,max_rev) VALUES(?,?,?,?) '
                   'ON CONFLICT(event_id) DO UPDATE SET max_seq=excluded.max_seq,max_rev=excluded.max_rev',
                   (event_id,known_kind,seq+1,version['rev']))
    db.execute('INSERT INTO knowledge(seq,status,source_sha256) VALUES(?,?,?)',
               (seq+1,'committed',source_sha))
    db.execute('UPDATE metadata SET value=? WHERE key=?',(str(seq+1),'latest_seq'))
    return {'batch_id':batch_id,'source_sha256':source_sha,'seq':seq+1,
            'event_count':len(versions),'duplicate':False}
